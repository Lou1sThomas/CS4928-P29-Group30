"""
Step 5 - Score every saved output against its target and apply the frozen decision rule.

Metrics (same for every condition):
  EXM : exact match after whitespace normalisation (all whitespace runs -> one space),
        the authors' normalisation. Primary metric.
  LEV : normalised Levenshtein similarity (rapidfuzz), 0..1. Secondary metric.
The model's code is the first ```java (or ```) block in its reply; the whole reply if none.

Usage: python scripts/score.py
Output: results/per_case.csv, results/summary_by_condition.csv,
        results/summary_by_project.csv, results/decision.md
"""
import csv
import json
import os
import re
from collections import defaultdict

from rapidfuzz.distance import Levenshtein

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CFG = json.load(open(os.path.join(ROOT, "config.json"), encoding="utf-8"))
RULE = CFG["decision_rule"]
CONDS = ["raw", "A_code_comment_removal", "B_review_comment_cleaning"]


def safe(name):
    return re.sub(r"[^A-Za-z0-9._-]+", "_", name)


def extract_code(text):
    m = re.search(r"```(?:java)?[ \t]*\n(.*?)```", text, re.S)
    return m.group(1) if m else text


def norm(s):
    return " ".join(s.split())


def main():
    rows = [json.loads(l) for l in open(os.path.join(ROOT, "data", "conditions.jsonl"), encoding="utf-8")]
    per = []
    for r in rows:
        f = os.path.join(ROOT, "results", "raw_outputs", r["condition"], safe(r["case_id"]) + ".json")
        rec = {"case_id": r["case_id"], "project": r["project"], "condition": r["condition"],
               "raw_output_file": os.path.relpath(f, ROOT)}
        if not os.path.exists(f):
            rec.update(status="MISSING_OUTPUT", exm="", lev="")
        else:
            reply = json.load(open(f, encoding="utf-8"))["response"]["choices"][0]["message"]["content"] or ""
            pred, tgt = norm(extract_code(reply)), norm(r["target_code"])
            rec.update(status="OK", exm=int(pred == tgt),
                       lev=round(Levenshtein.normalized_similarity(pred, tgt), 4))
        per.append(rec)

    out = os.path.join(ROOT, "results")
    with open(os.path.join(out, "per_case.csv"), "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=list(per[0].keys()))
        w.writeheader()
        w.writerows(per)

    def summarise(group_keys):
        g = defaultdict(list)
        for p in per:
            if p["status"] == "OK":
                g[tuple(p[k] for k in group_keys)].append(p)
        res = []
        for k, items in sorted(g.items()):
            res.append({**dict(zip(group_keys, k)), "n": len(items),
                        "exm_count": sum(i["exm"] for i in items),
                        "exm_pct": round(100 * sum(i["exm"] for i in items) / len(items), 1),
                        "mean_lev": round(sum(i["lev"] for i in items) / len(items), 4)})
        return res

    by_cond, by_proj = summarise(["condition"]), summarise(["project", "condition"])
    for name, data in [("summary_by_condition.csv", by_cond), ("summary_by_project.csv", by_proj)]:
        with open(os.path.join(out, name), "w", newline="", encoding="utf-8") as fh:
            w = csv.DictWriter(fh, fieldnames=list(data[0].keys()))
            w.writeheader()
            w.writerows(data)

    # ---------------- frozen decision rule
    n_cases = len({r["case_id"] for r in rows})
    missing = [p for p in per if p["status"] != "OK"]
    c = {d["condition"]: d for d in by_cond}
    lines = ["# Decision (generated by scripts/score.py from the frozen rule in config.json)", ""]
    if missing or len(c) < 3:
        verdict1 = "INCONCLUSIVE / BLOCKED"
        lines.append(f"{len(missing)} outputs missing - run is incomplete, so no verdict.")
    else:
        diffs = {k: (c[k]["exm_count"] - c["raw"]["exm_count"], c[k]["mean_lev"] - c["raw"]["mean_lev"])
                 for k in CONDS[1:]}
        ok = all(abs(d[0]) <= RULE["max_exm_case_difference"] and abs(d[1]) <= RULE["max_mean_lev_difference"]
                 for d in diffs.values())
        verdict1 = "REPRODUCED" if ok else "NOT REPRODUCED"
        lines.append("## RQ1 - raw vs cleaned (pooled, same fixed cases)")
        lines.append(f"Cases: {n_cases}. Raw: EXM {c['raw']['exm_count']}/{c['raw']['n']}, mean LEV {c['raw']['mean_lev']}")
        for k, (de, dl) in diffs.items():
            lines.append(f"- {k}: EXM {c[k]['exm_count']}/{c[k]['n']} (diff {de:+d} cases), "
                         f"mean LEV {c[k]['mean_lev']} (diff {dl:+.4f})")
        lines.append(f"Rule: REPRODUCED if every cleaned condition is within +/-{RULE['max_exm_case_difference']} "
                     f"EXM case(s) AND +/-{RULE['max_mean_lev_difference']} mean LEV of raw.")
        if c["raw"]["exm_count"] == 0 and all(c[k]["exm_count"] == 0 for k in CONDS[1:]):
            lines.append("Note: EXM is 0 in every condition (floor effect); the verdict rests on LEV.")
    lines += ["", f"**RQ1 status: {verdict1}**", ""]

    # RQ2: is the preprocessing effect the same in every project?
    lines.append("## RQ2 - does the effect change between projects?")
    p = defaultdict(dict)
    for d in by_proj:
        p[d["project"]][d["condition"]] = d
    pooled = {k: c[k]["mean_lev"] - c["raw"]["mean_lev"] for k in CONDS[1:]} if len(c) == 3 else {}
    consistent = True
    for proj, d in p.items():
        if len(d) < 3 or not pooled:
            consistent = None
            continue
        for k in CONDS[1:]:
            eff = d[k]["mean_lev"] - d["raw"]["mean_lev"]
            gap = eff - pooled[k]
            lines.append(f"- {proj} / {k}: effect {eff:+.4f} (pooled {pooled[k]:+.4f}, gap {gap:+.4f}); "
                         f"EXM {d['raw']['exm_count']}->{d[k]['exm_count']} of {d[k]['n']}")
            if abs(gap) > RULE["rq2_max_project_gap"]:
                consistent = False
    verdict2 = ("INCONCLUSIVE / BLOCKED" if consistent is None or missing else
                "CONSISTENT ACROSS PROJECTS (matches paper: small split effect)" if consistent else
                "PROJECT-DEPENDENT (differs from paper's small split effect)")
    lines += [f"Rule: consistent if each project's effect is within +/-{RULE['rq2_max_project_gap']} "
              f"mean LEV of the pooled effect, for both cleaned conditions.", "",
              f"**RQ2 status: {verdict2}**"]
    open(os.path.join(out, "decision.md"), "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
